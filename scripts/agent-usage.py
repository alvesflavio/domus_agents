# Idempotent migrations for existing databases (new columns added after initial deploy).
SQLITE_MIGRATIONS = [
    "ALTER TABLE invocations ADD COLUMN machine_id TEXT DEFAULT 'local'",
    "ALTER TABLE token_usage ADD COLUMN machine_id TEXT DEFAULT 'local'",
]
POSTGRES_MIGRATIONS = [
    "ALTER TABLE invocations ADD COLUMN IF NOT EXISTS machine_id TEXT DEFAULT 'local'",
    "ALTER TABLE token_usage ADD COLUMN IF NOT EXISTS machine_id TEXT DEFAULT 'local'",
]


class DbCompat:
    def __init__(self, raw, postgres=False):
        self.raw = raw
        self.postgres = postgres

    def executescript(self, script):
        if not self.postgres:
            return self.raw.executescript(script)
        with self.raw.cursor() as cur:
            for stmt in script.split(";"):
                if stmt.strip():
                    cur.execute(stmt)

    def execute(self, sql, params=()):
        if not self.postgres:
            return self.raw.execute(sql, params)
        sql = self._postgres_sql(sql)
        return self.raw.execute(sql, params)

    def executemany(self, sql, params):
        if not params:
            return None
        if not self.postgres:
            return self.raw.executemany(sql, params)
        sql = self._postgres_sql(sql)
        with self.raw.cursor() as cur:
            return cur.executemany(sql, params)

    def commit(self):
        return self.raw.commit()

    def rollback(self):
        return self.raw.rollback()

    def _postgres_sql(self, sql):
        sql = sql.replace("?", "%s")
        if sql.startswith("INSERT OR REPLACE INTO ingested_files"):
            return (
                "INSERT INTO ingested_files(path, mtime, size) VALUES (%s,%s,%s) "
                "ON CONFLICT(path) DO UPDATE SET "
                "mtime=EXCLUDED.mtime, size=EXCLUDED.size"
            )
        if sql.startswith("INSERT OR REPLACE INTO agent_map"):
            return (
                "INSERT INTO agent_map(agent_id, agent_type, source_file) VALUES (%s,%s,%s) "
                "ON CONFLICT(agent_id) DO UPDATE SET "
                "agent_type=EXCLUDED.agent_type, source_file=EXCLUDED.source_file"
            )
        return sql


def connect():
    if USE_POSTGRES:
        if psycopg is None:
            raise RuntimeError("psycopg is required when DATABASE_URL points to Postgres")
        raw = psycopg.connect(DATABASE_URL)
        con = DbCompat(raw, postgres=True)
        try:
            con.execute("SELECT pg_advisory_lock(hashtext(?))", ("domus_agent_usage_schema",))
            con.executescript(POSTGRES_SCHEMA)
            for sql in POSTGRES_MIGRATIONS:
                try:
                    con.execute(sql, ())
                except Exception:
                    # A failed DDL puts psycopg3 in an error state; roll back before
                    # attempting the next migration or the final commit.
                    con.rollback()
            con.commit()
        finally:
            try:
                con.execute("SELECT pg_advisory_unlock(hashtext(?))", ("domus_agent_usage_schema",))
                con.commit()
            except Exception:
                con.rollback()
        return con
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = DbCompat(sqlite3.connect(DB_PATH))
    con.executescript(SCHEMA)
    for sql in SQLITE_MIGRATIONS:
        try:
            con.execute(sql, ())
        except Exception:
            pass
    con.commit()
    return con


def file_changed(con, path: Path) -> bool:
    st = path.stat()
    row = con.execute("SELECT mtime, size FROM ingested_files WHERE path=?", (str(path),)).fetchone()
    return row is None or row[0] != st.st_mtime or row[1] != st.st_size


def mark_ingested(con, path: Path):
    st = path.stat()
    con.execute(
        "INSERT OR REPLACE INTO ingested_files(path, mtime, size) VALUES (?,?,?)",
        (str(path), st.st_mtime, st.st_size),
    )


def clear_file_rows(con, path: Path):
    con.execute("DELETE FROM invocations WHERE source_file=?", (str(path),))
    con.execute("DELETE FROM token_usage WHERE source_file=?", (str(path),))


