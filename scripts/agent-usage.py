"""Domus agent usage tracker.

Reads Claude Code and Codex session transcripts already on disk (zero model
tokens spent) and aggregates per-agent / per-project token usage into a
SQLite or Neon Postgres database (controlled by DATABASE_URL env var).

Usage:
  python scripts/agent-usage.py collect                   # balanced incremental ingest
  python scripts/agent-usage.py collect --platform codex  # ingest Codex only
  python scripts/agent-usage.py collect --max-updates 80  # bounded balanced batch
  python scripts/agent-usage.py report                    # summary tables
  python scripts/agent-usage.py report --agent security-reviewer
"""

