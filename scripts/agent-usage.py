def _check_thresholds(con) -> list[str]:
    """Return warning strings for threshold violations (runs after collect)."""
    msgs = []
    if USE_POSTGRES:
        ts7  = "CAST(ts AS timestamp) >= now() - (7  * interval '1 day')"
        ts30 = "CAST(ts AS timestamp) >= now() - (30 * interval '1 day')"
    else:
        ts7  = "ts >= datetime('now', '-7 days')"
        ts30 = "ts >= datetime('now', '-30 days')"

    # 1. Cache hit < 70% (all-time, min 10K total input-side tokens)
    try:
        rows = con.execute(
            "SELECT agent,"
            " COALESCE(SUM(cache_read_tokens), 0),"
            " COALESCE(SUM(input_tokens + cache_read_tokens + cache_create_tokens), 0)"
            " FROM token_usage WHERE agent IS NOT NULL"
            " GROUP BY agent"
        ).fetchall()
        for agent, cr, total in rows:
            if total >= 10_000 and (cr / total * 100) < 70:
                msgs.append(f"[CACHE ] {agent}: cache hit {cr/total*100:.0f}% < 70%")
    except Exception:
        pass

    # 2. Tokens/invocation spike > 50% vs all-time average (min 3 recent inv)
    try:
        r_tok = dict(con.execute(
            f"SELECT agent, COALESCE(SUM(output_tokens),0)"
            f" FROM token_usage WHERE agent IS NOT NULL AND {ts7} GROUP BY agent"
        ).fetchall())
        r_inv = dict(con.execute(
            f"SELECT agent, COUNT(*)"
            f" FROM invocations WHERE agent IS NOT NULL AND {ts7} GROUP BY agent"
        ).fetchall())
        h_tok = dict(con.execute(
            "SELECT agent, COALESCE(SUM(output_tokens),0)"
            " FROM token_usage WHERE agent IS NOT NULL GROUP BY agent"
        ).fetchall())
        h_inv = dict(con.execute(
            "SELECT agent, COUNT(*)"
            " FROM invocations WHERE agent IS NOT NULL GROUP BY agent"
        ).fetchall())
        for agent, inv_r in r_inv.items():
            inv_h = h_inv.get(agent, 0)
            if inv_r < 3 or inv_h < 5:
                continue
            avg_r = r_tok.get(agent, 0) / inv_r
            avg_h = h_tok.get(agent, 0) / inv_h
            if avg_h > 0 and avg_r > avg_h * 1.5:
                pct = (avg_r / avg_h - 1) * 100
                msgs.append(
                    f"[SPIKE ] {agent}: {avg_r/1000:.1f}K tok/inv (7d)"
                    f" vs {avg_h/1000:.1f}K histórico (+{pct:.0f}%)"
                )
    except Exception:
        pass

    # 3. Agents inactive for 30 days
    try:
        all_ag = {r[0] for r in con.execute(
            "SELECT DISTINCT agent FROM invocations WHERE agent IS NOT NULL"
        ).fetchall()}
        active = {r[0] for r in con.execute(
            f"SELECT DISTINCT agent FROM invocations WHERE agent IS NOT NULL AND {ts30}"
        ).fetchall()}
        for agent in sorted(all_ag - active):
            msgs.append(f"[INATIVO] {agent}: sem invocações nos últimos 30 dias")
    except Exception:
        pass

    return msgs


def _interleave_jobs(first, second):
    """Alternate platforms so long backfills do not starve either side."""
    jobs = []
    max_len = max(len(first), len(second))
    for idx in range(max_len):
        if idx < len(first):
            jobs.append(first[idx])
        if idx < len(second):
            jobs.append(second[idx])
    return jobs


def collect(args):
    con = connect()
    scanned = ingested = 0
    collect_locked = False

    try:
        if USE_POSTGRES:
            row = con.execute(
                "SELECT pg_try_advisory_lock(hashtext(?))",
                ("domus_agent_usage_collect",),
            ).fetchone()
            collect_locked = bool(row and row[0])
            if not collect_locked:
                raise RuntimeError("another Domus usage collection is already running")

        claude_files = sorted(
            CLAUDE_PROJECTS.glob("*/*.jsonl"),
            key=lambda p: p.stat().st_mtime,
            reverse=True,
        ) if CLAUDE_PROJECTS.exists() else []
        claude_subagent_files = sorted(
            CLAUDE_PROJECTS.glob("*/*/subagents/agent-*.jsonl"),
            key=lambda p: p.stat().st_mtime,
            reverse=True,
        ) \
            if CLAUDE_PROJECTS.exists() else []
        codex_files = []
        for base in CODEX_SESSION_DIRS:
            if base.exists():
                codex_files.extend(base.rglob("rollout-*.jsonl"))
        codex_files = sorted(codex_files, key=lambda p: p.stat().st_mtime, reverse=True)

        platform = getattr(args, "platform", "all")
        codex_jobs = [(p, ingest_codex_file) for p in codex_files]
        # Main sessions first: they populate agent_map used by subagent attribution.
        claude_jobs = [(p, ingest_claude_file) for p in claude_files]
        claude_jobs.extend((p, ingest_claude_subagent_file) for p in claude_subagent_files)

        if platform == "codex":
            jobs = codex_jobs
        elif platform == "claude":
            jobs = claude_jobs
        else:
            jobs = _interleave_jobs(codex_jobs, claude_jobs)

        for path, fn in jobs:
            scanned += 1
            if not file_changed(con, path):
                continue
            try:
                clear_file_rows(con, path)
                fn(con, path)
                mark_ingested(con, path)
                ingested += 1
                con.commit()
                if args.max_updates and ingested >= args.max_updates:
                    break
            except Exception as exc:
                # Roll back the partial writes for this file so the connection
                # stays usable for the remaining files (critical for psycopg3,
                # which enters InFailedSqlTransaction on any unhandled error).
                con.rollback()
                print(f"Warning: failed to ingest {path}: {exc}", file=__import__('sys').stderr)

        con.commit()
        dest = DATABASE_URL.split("@")[-1] if USE_POSTGRES else str(DB_PATH)
        print(f"Platform: {platform}")
        print(f"Scanned {scanned} files, ingested/updated {ingested}.")
        if args.max_updates:
            print(f"Max updates: {args.max_updates}")
        print(f"Database: {'neon:' if USE_POSTGRES else 'sqlite:'}{dest}")
        print(f"Machine:  {MACHINE_ID}")

        alerts = _check_thresholds(con)
        if alerts:
            print("\n--- Alertas de threshold ---")
            for msg in alerts:
                print(msg)
    finally:
        if USE_POSTGRES and collect_locked:
            try:
                con.execute("SELECT pg_advisory_unlock(hashtext(?))", ("domus_agent_usage_collect",))
                con.commit()
            except Exception:
                con.rollback()


